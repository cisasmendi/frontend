    <h2 class="text-2xl font-semibold text-[#6d0205]">¿Qué es una Pasantía?</h2>

    <p>
      La pasantía educativa ofrece a los alumnos la oportunidad de realizar
      actividades que complementen y amplíen su formación teórica. Esta práctica
      conecta a los alumnos con el sector productivo y de servicios, tanto
      público como privado, otorgándoles la posibilidad de conocer y participar
      en realidades institucionales y organizacionales diversas.
    </p>

    <p>
      El trabajo en equipo, la relación con superiores, la posibilidad de
      generar proyectos en relación a la tarea, y el trabajo interdisciplinario
      forman parte de esta experiencia pre-profesional, enriqueciendo la
      formación académica de los pasantes. La pasantía no solo conforma un
      antecedente valioso en el CV del futuro graduado, sino que también abre la
      posibilidad de generar un vínculo laboral en el futuro.
    </p>

    <p>
      Actualmente, la FCEyA recibe solicitudes de empresas para la difusión de
      búsquedas laborales dirigidas a estudiantes avanzados o recientes
      graduados.
    </p>
