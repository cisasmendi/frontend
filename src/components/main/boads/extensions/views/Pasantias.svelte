      <h3 class="text-xl pt-4 font-semibold text-[#6d0205]">
        Información para Alumnos y Empresas
      </h3>
      <div class="accordion-content links-documentos">
        <div class="space-y-4">
          <h3 class="text-2xl font-semibold text-[#6d0205]">
            Sistema de Pasantías Educativas para Alumnos
          </h3>

          <h4 class="text-xl font-semibold">Información para Alumnos</h4>
          <p>
            Todos los alumnos regulares de la Facultad de Ciencias Económicas
            pueden acceder a una pasantía a través de la Secretaría de
            Relaciones Institucionales (SRI). A través de esta, se gestiona el
            Sistema de Pasantías Educativas, realizando convenios con empresas
            y/u organismos públicos para facilitar la inserción laboral de los
            alumnos en el ámbito profesional.
          </p>

          <h3 class="text-xl font-semibold">
            Condiciones Requeridas para Postularse como Pasante
          </h3>
          <ul class="list-disc list-inside mb-4">
            <li>
              Ser alumno regular de grado de FCEyA (Graduados abstenerse,
              independientemente de estar cursando otra carrera de grado).
            </li>
            <li>No estar asignado a otra pasantía.</li>
            <li>Ser mayor de 18 años.</li>
          </ul>

          <h3 class="text-xl font-semibold">
            ¿Cómo Inscribirse en el Sistema de Pasantías Educativas?
          </h3>
          <p>
            Los alumnos interesados en acceder al Sistema de Pasantes Educativas
            pueden enviar su CV por correo electrónico para ser incorporados en
            la base de datos de la Facultad.
          </p>

          <h3 class="text-xl font-semibold">Información General</h3>
          <p>
            Las actividades de las pasantías se llevarán a cabo en las
            instalaciones de la empresa, que deberán cumplir con las condiciones
            de higiene y seguridad dispuestas por la Ley de Higiene y Seguridad
            del Trabajo N° 19.587. Además, la empresa incorporará a los pasantes
            en el ámbito de la Ley de Riesgos del Trabajo N° 24.557 y les
            otorgará cobertura de salud conforme a la Ley de Obras Sociales N°
            23.660.
          </p>

          <h3 class="text-xl font-semibold">Obligaciones del Pasante</h3>
          <ul class="list-disc list-inside mb-4">
            <li>
              Ajustarse a los horarios, normas y reglamentos internos de la
              empresa, de acuerdo con la legislación vigente.
            </li>
            <li>
              Tratar la información confidencial como tal, según sea clasificada
              por la empresa.
            </li>
          </ul>
          <p>
            El incumplimiento de estas obligaciones podrá causar la rescisión de
            la pasantía por parte de la empresa, previo aviso a La Facultad.
          </p>

          <h3 class="text-xl font-semibold">Duración y Renovación</h3>
          <p>
            Las pasantías tendrán una duración mínima de 2 meses y un máximo de
            12 meses, con una carga semanal de hasta 20 horas (jornadas no
            superiores a 6.30 horas diarias). Tras el máximo de 12 meses, se
            puede renovar la pasantía por hasta 6 meses adicionales mediante un
            nuevo acuerdo individual entre las partes.
          </p>

          <h3 class="text-xl font-semibold">Rescisión o Suspensión</h3>
          <p>
            La pasantía puede revocarse si el pasante no cumple con las
            obligaciones, o si las tareas asignadas no corresponden con lo
            convenido. Cualquier rescisión deberá ser comunicada con una
            antelación de al menos 30 días.
          </p>

          <h3 class="text-xl font-semibold">Retribución</h3>
          <p>
            Los pasantes recibirán una retribución mensual en calidad de
            asignación estímulo, financiada por la empresa. El monto mínimo se
            calculará sobre el salario básico del convenio colectivo aplicable,
            proporcional a la carga horaria de la pasantía. En caso de no
            existir convenio colectivo, se utilizará el salario mínimo, vital y
            móvil.
          </p>

          <h3 class="text-xl font-semibold">
            Información para Empresas y Organismos Públicos
          </h3>

          <h3 class="text-xl font-semibold">
            Requisitos para la Incorporación de Pasantes
          </h3>
          <p>
            Las empresas y organismos definidos en los art. 1 y 2 de la Ley
            26.427 y en el art. 2 de la Resolución Conjunta del MTEySS y
            Ministerio de Educación Nº 825-338/2009 deberán firmar un Convenio
            Marco de Pasantías con la Facultad de Ciencias Económicas y de
            Administración. La documentación necesaria para la confección del
            convenio es la siguiente:
          </p>
          <ul class="list-disc list-inside mb-4">
            <li>
              <strong>Personas físicas:</strong> Constancia de inscripción ante la
              AFIP y fotocopia de DNI.
            </li>
            <li>
              <strong>Personas Jurídicas:</strong> Constancia de inscripción ante
              la Dirección de Personas Jurídicas y ante la AFIP, copia del estatuto
              o contrato social, copia del acta de designación de autoridades o poder
              de la persona autorizada a firmar en representación de la empresa,
              y fotocopia de DNI.
            </li>
          </ul>

          <h3 class="text-xl font-semibold">Solicitud de Pasantes</h3>
          <p>
            Para solicitar pasantes de la Facultad de Ciencias Económicas, las
            empresas u organismos públicos o privados deberán comunicarse con la
            Secretaría de Relaciones Institucionales (SRI) para solicitar los
            formularios que incluyen especificaciones, datos y perfil académico
            requerido para los alumnos. Se enviará un número mayor de alumnos
            que el de vacantes disponibles para que la entidad realice la
            selección. La base de datos incluye información sobre cantidad de
            materias, carrera, promedio, conocimientos de idiomas y computación,
            entre otros.
          </p>

          <h3 class="text-xl font-semibold">
            Convenio Individual de Pasantías
          </h3>
          <p>
            Una vez enviado el listado de alumnos a la empresa, esta deberá
            comunicar a la SRI los nombres de los alumnos seleccionados para la
            pasantía. Luego se firmará el Acta Acuerdo Individual de Pasantía,
            por triplicado. Las pasantías tendrán una duración mínima de dos (2)
            meses y máxima de un (1) año, con una carga horaria semanal de hasta
            veinte (20) horas, distribuidas de lunes a viernes en jornada
            diurna. Cada jornada no podrá superar las seis horas y treinta
            minutos (6:30). Cumplido el plazo máximo, la vacante puede renovarse
            por hasta seis (6) meses adicionales mediante un nuevo convenio.
          </p>

          <h3 class="text-xl font-semibold">Retribución y Beneficios</h3>
          <p>
            Los pasantes recibirán una asignación estímulo no remunerativa
            calculada proporcionalmente sobre la base de los valores
            establecidos para la categoría asimilable del convenio colectivo de
            trabajo aplicable. En ausencia de convenio colectivo, se aplicará el
            salario mínimo vital y móvil. Además, los pasantes tendrán acceso a
            los beneficios y licencias acordados al personal, siempre que sean
            compatibles con la naturaleza no laboral de la pasantía.
          </p>

          <h3 class="text-xl font-semibold">Cupo Máximo de Pasantes</h3>
          <p>El cupo máximo de pasantes se fija según la siguiente escala:</p>
          <ul class="list-disc list-inside mb-4">
            <li>
              <strong>Empresas de hasta 200 trabajadores:</strong> Un (1) pasante
              por cada diez (10) trabajadores en relación de dependencia por tiempo
              indeterminado.
            </li>
            <li>
              <strong>Empresas de más de 201 trabajadores:</strong> Siete (7) por
              ciento de la planta de personal.
            </li>
            <li>
              <strong
                >Organismos o entidades de la Administración Pública:</strong
              > El número de pasantes no podrá exceder del siete (7) por ciento de
              la planta de personal financiada y aprobada en la normativa presupuestaria.
            </li>
          </ul>

          <h3 class="text-xl font-semibold">
            Seguimiento del Desempeño de los Pasantes
          </h3>
          <p>
            La SRI realizará el seguimiento del desempeño de los pasantes
            mediante un mecanismo de control y evaluación elaborado por los
            docentes guía designados. Dentro de los treinta (30) días
            posteriores a la finalización de la pasantía, los tutores deberán
            remitir un informe con la evaluación del desempeño del pasante a la
            unidad académica. Se extenderá un certificado de pasantía educativa
            en el que constará la duración y actividad desarrollada por el
            pasante.
          </p>

          <h3 class="text-xl font-semibold">Formularios de Pasantías</h3>
          <p>
            Los formularios necesarios para la gestión de pasantías están
            disponibles en la Secretaría de Relaciones Institucionales.
          </p>
